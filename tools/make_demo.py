"""Generate MetaPy's SYNTHETIC demo workbook (not real studies; for testing only)."""
import numpy as np, pandas as pd, sys
from pathlib import Path
rng = np.random.default_rng(7)
out = Path(sys.argv[1] if len(sys.argv) > 1 else "examples")
rows = []
names = ["Ahmed", "Baker", "Chen", "Diaz", "Evans", "Farooq", "Garcia", "Haddad", "Ito", "Jones", "Khan", "Lopez", "Malik", "Nguyen", "Okafor", "Patel"]
styles = ["msd", "msd", "msd", "msd", "msd", "median", "median", "text", "t", "mdci", "pthr", "smd", "gci", "nosd", "multi", "msd"]
countries = ["Pakistan", "UK", "China", "Spain", "USA", "Pakistan", "Mexico", "Jordan", "Japan", "UK", "Pakistan", "Spain", "Pakistan", "Vietnam", "Nigeria", "India"]
for i, (nm, st) in enumerate(zip(names, styles)):
    year = 2008 + i
    delivery = "Online" if i % 3 == 0 else "Face-to-face"
    rob = "High" if i % 4 == 0 else "Low"
    age = round(float(rng.uniform(22, 60)), 1)
    true_d = -0.45 + (0.15 if delivery == "Online" else 0) + rng.normal(0, 0.15)
    arms = ["CBT", "Mindfulness"] if st == "multi" else ["CBT"]
    nc = int(rng.integers(25, 80))
    for arm in arms:
        ni = int(rng.integers(25, 80))
        sd = 6.0
        pre_i, pre_c = 25 + rng.normal(0, 1), 25 + rng.normal(0, 1)
        post_c = pre_c - 1 + rng.normal(0, 0.5)
        post_i = post_c + (true_d + rng.normal(0, 0.1)) * sd
        sdi, sdc = sd * rng.uniform(0.85, 1.15), sd * rng.uniform(0.85, 1.15)
        r = dict(Study=f"{nm} {year}", Year=year, Outcome="Anxiety (HADS-A)", Intervention_Arm=arm, Country=countries[i],
                 Delivery=delivery, Mean_Age=age, Risk_of_Bias=rob, N_I=ni, N_C=nc)
        if st in ("msd", "multi"):
            r.update(Mean_Pre_I=round(pre_i, 2), SD_Pre_I=round(sd, 2), Mean_Pre_C=round(pre_c, 2), SD_Pre_C=round(sd, 2),
                     Mean_Post_I=round(post_i, 2), SD_Post_I=round(sdi, 2), Mean_Post_C=round(post_c, 2), SD_Post_C=round(sdc, 2))
            if i % 2 == 0:
                r.update(r_prepost_I=0.62, r_prepost_C=0.58)
        elif st == "median":
            r.update(Median_Post_I=round(post_i, 1), Q1_Post_I=round(post_i - 4, 1), Q3_Post_I=round(post_i + 4.2, 1),
                     Median_Post_C=round(post_c, 1), Q1_Post_C=round(post_c - 4.1, 1), Q3_Post_C=round(post_c + 3.9, 1))
        elif st == "text":
            r.update(**{"Mean (SD) post I": f"{post_i:.1f} ({sdi:.1f})", "Mean (SD) post C": f"{post_c:.1f} ({sdc:.1f})"})
        elif st == "t":
            sp = np.sqrt(((ni - 1) * sdi ** 2 + (nc - 1) * sdc ** 2) / (ni + nc - 2))
            r.update(t=round((post_i - post_c) / (sp * np.sqrt(1 / ni + 1 / nc)), 2))
        elif st == "mdci":
            se = np.sqrt(sdi ** 2 / ni + sdc ** 2 / nc); md = post_i - post_c
            r.update(**{"MD (95% CI)": f"{md:.2f} ({md - 1.96 * se:.2f} to {md + 1.96 * se:.2f})"})
        elif st == "pthr":
            r.update(MD=round(post_i - post_c, 2), p="<0.05")
        elif st == "smd":
            r.update(SMD=round(true_d, 2), SMD_SE=round(np.sqrt(1 / ni + 1 / nc + true_d ** 2 / (2 * (ni + nc))), 3))
        elif st == "gci":
            se = np.sqrt(1 / ni + 1 / nc + true_d ** 2 / (2 * (ni + nc)))
            r.update(Hedges_g=round(true_d, 2), g_CI_lower=round(true_d - 1.96 * se, 2), g_CI_upper=round(true_d + 1.96 * se, 2))
        elif st == "nosd":
            r.update(Mean_Post_I=round(post_i, 2), Mean_Post_C=round(post_c, 2))
        rows.append(r)
anx = pd.DataFrame(rows)
# binary outcome sheet
brows = []
for i in range(8):
    nm = names[i]; year = 2008 + i
    ni, nc = int(rng.integers(40, 120)), int(rng.integers(40, 120))
    pc = rng.uniform(0.25, 0.4); pi = min(0.9, pc * np.exp(rng.normal(0.35, 0.2)))
    ei, ec = int(rng.binomial(ni, pi)), int(rng.binomial(nc, pc))
    r = dict(Study=f"{nm} {year}", Year=year, Outcome="Remission", Delivery="Online" if i % 3 == 0 else "Face-to-face", N_I=ni, N_C=nc)
    if i == 5:
        orr = (ei / (ni - ei)) / (ec / (nc - ec)); se = np.sqrt(1 / ei + 1 / (ni - ei) + 1 / ec + 1 / (nc - ec))
        r.update(**{"OR (95% CI)": f"{orr:.2f} ({np.exp(np.log(orr) - 1.96 * se):.2f}, {np.exp(np.log(orr) + 1.96 * se):.2f})"})
    elif i == 6:
        r.update(**{"Percent_I": f"{100 * ei / ni:.1f}%", "Percent_C": f"{100 * ec / nc:.1f}%"})
    else:
        r.update(Events_I=ei, Events_C=ec)
    brows.append(r)
binary = pd.DataFrame(brows)
out.mkdir(parents=True, exist_ok=True)
with pd.ExcelWriter(out / "MetaPy_SYNTHETIC_demo.xlsx") as xw:
    pd.DataFrame({"README": ["SYNTHETIC TEST DATA generated by tools/make_demo.py. These are not real studies.",
                             "Use only to try MetaPy. Do not cite or publish."]}).to_excel(xw, "README", index=False)
    anx.to_excel(xw, "Anxiety", index=False)
    binary.to_excel(xw, "Remission", index=False)
anx.to_csv(out / "MetaPy_SYNTHETIC_demo_anxiety.csv", index=False)
print(anx.shape, binary.shape)
